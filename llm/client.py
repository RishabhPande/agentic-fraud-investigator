"""LLM client: pluggable language-model backend.

Two implementations, zero dependencies:

- MockLLM (default): deterministic, template-driven report generation.
  Used by tests and the demo so everything runs offline.
- AnthropicLLM: calls the Anthropic Messages API with urllib, but only
  when the ANTHROPIC_API_KEY environment variable is set.

Set the backend with the AGENT_LLM_BACKEND env var ('mock' | 'anthropic').
"""

from __future__ import annotations

import json
import os
import re
import urllib.request


class LLMClient:
    """Interface every backend implements."""

    def complete(self, prompt: str, system: str | None = None) -> str:
        raise NotImplementedError


class MockLLM(LLMClient):
    """Deterministic mock: renders an analyst report from the case JSON.

    The summarizer embeds the case as a CASE_JSON block in the prompt;
    the mock parses it back out and fills a fixed report template. Fully
    deterministic, so demos and tests are reproducible.
    """

    def complete(self, prompt: str, system: str | None = None) -> str:
        match = re.search(r"CASE_JSON:\s*(\{.*\})", prompt, re.DOTALL)
        if not match:
            return "MOCK-LLM: no case data found in prompt."
        case = json.loads(match.group(1))

        lines = []
        lines.append("CASE SUMMARY")
        lines.append("=" * 60)
        a = case["alert"]
        lines.append(f"Alert {a['alert_id']} | Account {a['account_id']}")
        lines.append(
            f"${a['amount']:,.2f} at {a['merchant']} "
            f"({a['merchant_category']}, {a['channel']})"
        )
        lines.append(
            f"Priority: {case['priority'].upper()} | "
            f"Risk score: {case['risk_score']:.2f} | "
            f"Verdict: {case['verdict'].upper()}"
        )
        lines.append("")
        lines.append("WHY IT WAS FLAGGED")
        for reason in case["triage_reasons"]:
            lines.append(f"  - {reason}")
        lines.append("")
        lines.append("EVIDENCE")
        for ev in case["evidence"]:
            lines.append(f"  - {ev['name']}: {ev['value']} (signal {ev['signal']:.2f})")
        lines.append("")
        lines.append("TOP RISK DRIVERS")
        for name, share in sorted(
            case["contributions"].items(), key=lambda kv: kv[1], reverse=True
        )[:3]:
            lines.append(f"  - {name}: {share:.0%} of score")
        lines.append("")
        lines.append("ANALYST NOTE")
        if case["verdict"] == "block":
            lines.append(
                "  Recommend immediate block and manual review. Multiple "
                "independent signals corroborate fraudulent activity."
            )
        elif case["verdict"] == "review":
            lines.append(
                "  Recommend queueing for analyst review. Signals are "
                "suspicious but not conclusive on their own."
            )
        else:
            lines.append(
                "  No strong fraud indicators. Recommend approving with "
                "standard monitoring."
            )
        lines.append("")
        lines.append("(generated by MockLLM -- deterministic offline backend)")
        return "\n".join(lines)


class AnthropicLLM(LLMClient):
    """Real backend: Anthropic Messages API over stdlib urllib.

    Requires ANTHROPIC_API_KEY in the environment. Raises RuntimeError
    at construction time if the key is missing, so misconfiguration
    fails fast instead of silently degrading.
    """

    API_URL = "https://api.anthropic.com/v1/messages"
    API_VERSION = "2023-06-01"
    MODEL = "claude-sonnet-4-5-20250929"
    MAX_TOKENS = 1024

    def __init__(self) -> None:
        self.api_key = os.environ.get("ANTHROPIC_API_KEY")
        if not self.api_key:
            raise RuntimeError("ANTHROPIC_API_KEY is not set")

    def complete(self, prompt: str, system: str | None = None) -> str:
        body: dict = {
            "model": self.MODEL,
            "max_tokens": self.MAX_TOKENS,
            "messages": [{"role": "user", "content": prompt}],
        }
        if system:
            body["system"] = system
        req = urllib.request.Request(
            self.API_URL,
            data=json.dumps(body).encode("utf-8"),
            headers={
                "content-type": "application/json",
                "x-api-key": self.api_key,
                "anthropic-version": self.API_VERSION,
            },
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=60) as resp:
            payload = json.loads(resp.read().decode("utf-8"))
        blocks = payload.get("content", [])
        texts = [b.get("text", "") for b in blocks if b.get("type") == "text"]
        return "\n".join(texts).strip()


def get_llm() -> LLMClient:
    """Factory: picks the backend from AGENT_LLM_BACKEND (default 'mock')."""
    backend = os.environ.get("AGENT_LLM_BACKEND", "mock").lower()
    if backend == "anthropic":
        return AnthropicLLM()
    return MockLLM()
